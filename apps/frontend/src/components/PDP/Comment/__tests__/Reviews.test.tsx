import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import Comment from '../index';
import Add from '../Add';
import UserService from '@/services/user';
import { productReviewService } from '@/services/product/product-review.service';
import { useCurrentUser } from '@/hooks/useCurrentUser';
const push = jest.fn();
jest.mock('next/navigation', () => ({ useRouter: () => ({ push }) }));
jest.mock('@/hooks/useCurrentUser');
jest.mock('@/services/user', () => ({ __esModule: true, default: { me: jest.fn() } }));
jest.mock('@/services/product/product-review.service', () => ({ productReviewService: { getProductReviews: jest.fn() } }));
jest.mock('../CommentModal', () => ({ isOpen }: any) => isOpen ? <div role="dialog">comment editor</div> : null);
jest.mock('../ListItem', () => ({ review }: any) => <p>{review.Content}</p>);
jest.mock('@/components/Kits/Modal', () => () => null);
const userHook = useCurrentUser as jest.Mock;
const review = (id: number) => ({ id, Content: `review ${id}`, Rate: 5, createdAt: '2026-01-01', Status: 'Accepted' }) as any;
beforeEach(() => { jest.clearAllMocks(); userHook.mockReturnValue({ user: null, isLoading: true }); });
it('checks the session on demand while identity restoration is pending', async () => {
 (UserService.me as jest.Mock).mockResolvedValue({ id: 1 });
 render(<Add rating={0} rateCount={0} productId="1" />);
 const button = screen.getByRole('button', { name: 'افزودن نظر' });
 fireEvent.click(button); fireEvent.click(button);
 expect(UserService.me).toHaveBeenCalledTimes(1);
 expect(push).not.toHaveBeenCalled();
 await screen.findByRole('dialog');
});
it('appends the next public page and replaces it with a server-sorted result', async () => {
 (productReviewService.getProductReviews as jest.Mock).mockResolvedValueOnce({ data: [review(1), review(2)], meta: { totalPages: 2 } }).mockResolvedValueOnce({ data: [review(3)], meta: { totalPages: 1 } });
 render(<Comment rating={5} rateCount={3} productId="1" productReviews={[review(1)]} initialTotalPages={2} />);
 fireEvent.click(screen.getByRole('button', { name: 'دیدگاه‌های بیشتر' }));
 await screen.findByText('review 2'); expect(screen.getAllByText('review 1')).toHaveLength(1);
 expect(productReviewService.getProductReviews).toHaveBeenCalledWith('1', { page: 2, sort: 'createdAt:desc' });
 fireEvent.click(screen.getByRole('button', { name: 'جدیدترین' }));
 fireEvent.click(screen.getByRole('button', { name: 'بیشترین امتیاز' }));
 await screen.findByText('review 3');
 await waitFor(() => expect(screen.queryByText('review 1')).not.toBeInTheDocument());
 expect(productReviewService.getProductReviews).toHaveBeenLastCalledWith('1', { page: 1, sort: 'Rate:desc' });
 expect(screen.queryByRole('button', { name: 'دیدگاه‌های بیشتر' })).not.toBeInTheDocument();
});
